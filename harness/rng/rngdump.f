      PROGRAM RNGDUMP
C     WRITES THE FIRST N drand48 VALUES (MAGBOLTZ SHIM OVER RM48)
C     AS RAW LITTLE-ENDIAN FLOAT64 TO THE FILE GIVEN AS 2ND ARGUMENT
      IMPLICIT NONE
      DOUBLE PRECISION drand48,X,RDUM
      INTEGER*8 I,N
      CHARACTER*256 ARG
      CALL GET_COMMAND_ARGUMENT(1,ARG)
      READ(ARG,*) N
      CALL GET_COMMAND_ARGUMENT(2,ARG)
      OPEN(7,FILE=ARG,ACCESS='STREAM',FORM='UNFORMATTED',
     /STATUS='REPLACE')
      RDUM=0.0D0
      DO 10 I=1,N
      X=drand48(RDUM)
      WRITE(7) X
   10 CONTINUE
      CLOSE(7)
      END
